from math import cos, pi, sin


def polygon(coordinates):
    values = [float(value) for value in coordinates.split()]
    return tuple(zip(values[::2], values[1::2]))


def oval(x, y, rx, ry, angle=0):
    angle *= pi / 180
    return tuple(
        (x + rx * cos(t) * cos(angle) - ry * sin(t) * sin(angle),
         y + rx * cos(t) * sin(angle) + ry * sin(t) * cos(angle))
        for t in (i * 2 * pi / 48 for i in range(48))
    )


def cut(shape):
    return False, shape


